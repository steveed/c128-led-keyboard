#!/usr/bin/env python3
"""Regenerate main/keymap.h from layout/switches.json.

Two scanned matrices, picked at build time by BOARD_REV3:

  bench (default)  the rev 2.3 board on the bench rig: 8 x 12, wired in the C128's own
                   ROW/COL order, so physical position n is host position n; column 11
                   carries the three lock keys
  rev 3            the rev 3 board: 6 x 20 following the board's rows and columns
                   (pcb/tools/layout.py physical_matrix); the CH446Q still presents the
                   C128 matrix, so every position carries its host position

For each scanned position the header gives the key legend (KEY_NAMES) and what it does on
the host (KEY_HOST): a host row and column for the crosspoint, a lock key, or nothing.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "pcb", "tools"))
import layout  # noqa: E402

OUT = os.path.join(HERE, "..", "main", "keymap.h")
LOCKS = {"SW89": ("HOST_LOCK_SHIFT", "ShiftLock"), "SW91": ("HOST_LOCK_CAPS", "CapsLock"),
         "SW92": ("HOST_LOCK_4080", "40/80")}
BENCH_LOCK_POS = {"SW89": (0, 11), "SW91": (1, 11), "SW92": (2, 11)}


def host(sw):
    """What a key does on the C128: 'row << 4 | col' for the crosspoint, or a lock key."""
    if sw["ref"] in LOCKS:
        return LOCKS[sw["ref"]][0]
    r = re.match(r"ROW(\d+)", sw["row"] or "")
    c = re.match(r"COL(\d+)", sw["col"] or "")
    return f"HOST({r.group(1)}, {c.group(1)})"


def tables(switches, pos, rows, cols):
    names = [["NULL"] * cols for _ in range(rows)]
    hosts = [["HOST_NONE"] * cols for _ in range(rows)]
    for sw in switches:
        if sw["ref"] not in pos:
            continue
        r, c = pos[sw["ref"]]
        name = LOCKS[sw["ref"]][1] if sw["ref"] in LOCKS else sw["val"]
        names[r][c] = '"%s"' % name.replace('"', '\\"')
        hosts[r][c] = host(sw)
    out = [f"#define MATRIX_ROWS {rows}", f"#define MATRIX_COLS {cols}",
           "static const char *const KEY_NAMES[MATRIX_ROWS][MATRIX_COLS] = {"]
    out += ["    {" + ", ".join(row) + "}," for row in names] + ["};"]
    out += ["static const uint8_t KEY_HOST[MATRIX_ROWS][MATRIX_COLS] = {"]
    out += ["    {" + ", ".join(row) + "}," for row in hosts] + ["};"]
    return out


def main():
    switches = [s for s in layout.load_switches() if s["val"] != "Restore"]
    bench = {}
    for sw in switches:
        if sw["ref"] in BENCH_LOCK_POS:
            bench[sw["ref"]] = BENCH_LOCK_POS[sw["ref"]]
        else:
            bench[sw["ref"]] = (int(sw["row"][3:]), int(sw["col"][3:]))
    rev3 = layout.physical_matrix()
    lines = [
        "// Generated by firmware/tools/gen_keymap.py from layout/switches.json.  Do not edit.",
        "// KEY_NAMES[row][col]: scanned position -> key legend.  KEY_HOST[row][col]: what the key",
        "// does on the C128: HOST(row, col) is a crosspoint, HOST_LOCK_* a lock key, HOST_NONE no key.",
        "// BOARD_REV3 picks the rev 3 board's 6 x 20 matrix; otherwise the bench rig's rev 2.3 board,",
        "// wired in the C128's own order (column 11 carries the lock keys).",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#define HOST_COLS 11",
        "#define HOST(r, c) ((r) << 4 | (c))",
        "#define HOST_LOCK_SHIFT 0xF0",
        "#define HOST_LOCK_CAPS 0xF1",
        "#define HOST_LOCK_4080 0xF2",
        "#define HOST_NONE 0xFF",
        "#if BOARD_REV3",
    ]
    lines += tables(switches, rev3, layout.PHYS_ROWS, layout.PHYS_COLS)
    lines += ["#else"] + tables(switches, bench, 8, 12) + ["#endif"]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
