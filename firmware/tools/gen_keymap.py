#!/usr/bin/env python3
"""Regenerate main/keymap.h from layout/switches.json.

Two scanned matrices, picked at build time by BOARD_REV3:

  bench (default)  the rev 2.3 board on the bench rig: 8 x 12, wired in the C128's own
                   ROW/COL order, so physical position n is host position n; column 11
                   carries the three lock keys
  rev 3            the rev 3 board: 6 x 20 following the board's rows and columns
                   (pcb/tools/layout.py physical_matrix); the CH446Q still presents the
                   C128 matrix, so every position carries its host position

For each scanned position the header gives the key legend (KEY_NAMES) and what it does on
the host (KEY_HOST): a host row and column for the crosspoint, a lock key, or nothing.

It also writes main/crosspoint_map.h: which CH446Q X and Y pin carries each host column and
row.  The bench rig wires them in order (X n = COL n, Y n = ROW n); the rev 3 board orders
them for routing (pcb/tools/gen_sch.py XP_X_OF_COL / XP_Y_OF_ROW, via pcb/tools/pinmaps.json).

And main/led_map.h, for the LED engine: the chain length, which LED sits under each scanned
key (LED_OF_KEY), where every LED is on the board (LED_X / LED_Y, 0-255 across the switch
field) and which LEDs are the lock keys'.  On the rev 3 board the chain is
pcb/tools/layout.py led_chain (lock keys first, then a snake through the rows).  The bench
rig drives a 60-LED strip instead: keys map onto it by their x position.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "pcb", "tools"))
import layout  # noqa: E402

OUT = os.path.join(HERE, "..", "main", "keymap.h")
XP_OUT = os.path.join(HERE, "..", "main", "crosspoint_map.h")
LED_OUT = os.path.join(HERE, "..", "main", "led_map.h")
BENCH_STRIP = 60
PINMAPS = os.path.join(HERE, "..", "..", "pcb", "tools", "pinmaps.json")
LOCKS = {"SW89": ("HOST_LOCK_SHIFT", "ShiftLock"), "SW91": ("HOST_LOCK_CAPS", "CapsLock"),
         "SW92": ("HOST_LOCK_4080", "40/80")}
BENCH_LOCK_POS = {"SW89": (0, 11), "SW91": (1, 11), "SW92": (2, 11)}


def host(sw):
    """What a key does on the C128: 'row << 4 | col' for the crosspoint, or a lock key."""
    if sw["ref"] in LOCKS:
        return LOCKS[sw["ref"]][0]
    r = re.match(r"ROW(\d+)", sw["row"] or "")
    c = re.match(r"COL(\d+)", sw["col"] or "")
    return f"HOST({r.group(1)}, {c.group(1)})"


def tables(switches, pos, rows, cols):
    names = [["NULL"] * cols for _ in range(rows)]
    hosts = [["HOST_NONE"] * cols for _ in range(rows)]
    for sw in switches:
        if sw["ref"] not in pos:
            continue
        r, c = pos[sw["ref"]]
        name = LOCKS[sw["ref"]][1] if sw["ref"] in LOCKS else sw["val"]
        names[r][c] = '"%s"' % name.replace('"', '\\"')
        hosts[r][c] = host(sw)
    out = [f"#define MATRIX_ROWS {rows}", f"#define MATRIX_COLS {cols}",
           "static const char *const KEY_NAMES[MATRIX_ROWS][MATRIX_COLS] = {"]
    out += ["    {" + ", ".join(row) + "}," for row in names] + ["};"]
    out += ["static const uint8_t KEY_HOST[MATRIX_ROWS][MATRIX_COLS] = {"]
    out += ["    {" + ", ".join(row) + "}," for row in hosts] + ["};"]
    return out


def main():
    switches = [s for s in layout.load_switches() if s["val"] != "Restore"]
    bench = {}
    for sw in switches:
        if sw["ref"] in BENCH_LOCK_POS:
            bench[sw["ref"]] = BENCH_LOCK_POS[sw["ref"]]
        else:
            bench[sw["ref"]] = (int(sw["row"][3:]), int(sw["col"][3:]))
    rev3 = layout.physical_matrix()
    lines = [
        "// Generated by firmware/tools/gen_keymap.py from layout/switches.json.  Do not edit.",
        "// KEY_NAMES[row][col]: scanned position -> key legend.  KEY_HOST[row][col]: what the key",
        "// does on the C128: HOST(row, col) is a crosspoint, HOST_LOCK_* a lock key, HOST_NONE no key.",
        "// BOARD_REV3 picks the rev 3 board's 6 x 20 matrix; otherwise the bench rig's rev 2.3 board,",
        "// wired in the C128's own order (column 11 carries the lock keys).",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#define HOST_COLS 11",
        "#define HOST(r, c) ((r) << 4 | (c))",
        "#define HOST_LOCK_SHIFT 0xF0",
        "#define HOST_LOCK_CAPS 0xF1",
        "#define HOST_LOCK_4080 0xF2",
        "#define HOST_NONE 0xFF",
        "#if BOARD_REV3",
    ]
    lines += tables(switches, rev3, layout.PHYS_ROWS, layout.PHYS_COLS)
    lines += ["#else"] + tables(switches, bench, 8, 12) + ["#endif"]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT)

    xp = json.load(open(PINMAPS, encoding="utf-8"))["crosspoint_rev3"]
    arr = lambda v: "{" + ", ".join(str(n) for n in v) + "}"
    lines = [
        "// Generated by firmware/tools/gen_keymap.py from pcb/tools/pinmaps.json.  Do not edit.",
        "// CH446Q pin for each host line: XP_X_OF_COL[host column] is the X pin, XP_Y_OF_ROW[host row]",
        "// the Y pin.  The bench rig wires them in order; the rev 3 board in the order that routes.",
        "#pragma once",
        "#include <stdint.h>",
        "#if BOARD_REV3",
        f"static const uint8_t XP_X_OF_COL[11] = {arr(xp['x_of_col'])};",
        f"static const uint8_t XP_Y_OF_ROW[8] = {arr(xp['y_of_row'])};",
        "#else",
        f"static const uint8_t XP_X_OF_COL[11] = {arr(range(11))};",
        f"static const uint8_t XP_Y_OF_ROW[8] = {arr(range(8))};",
        "#endif",
    ]
    with open(XP_OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", XP_OUT)

    led_map(switches, rev3, bench)


def led_tables(chain_xy, led_of_ref, pos, rows, cols, locks):
    """C tables for one board: chain_xy is each LED's (x, y) in mm, in chain order."""
    xs = [x for x, _ in chain_xy]
    ys = [y for _, y in chain_xy]
    span = lambda v, lo, hi: 128 if hi == lo else round((v - lo) * 255 / (hi - lo))
    lx = [span(x, min(xs), max(xs)) for x in xs]
    ly = [span(y, min(ys), max(ys)) for y in ys]
    grid = [["LED_NONE"] * cols for _ in range(rows)]
    for ref, (r, c) in pos.items():
        if ref in led_of_ref:
            grid[r][c] = str(led_of_ref[ref])
    arr = lambda v: "{" + ", ".join(str(n) for n in v) + "}"
    out = [f"#define LED_CHAIN_LEN {len(chain_xy)}",
           "static const uint8_t LED_OF_KEY[MATRIX_ROWS][MATRIX_COLS] = {"]
    out += ["    {" + ", ".join(row) + "}," for row in grid] + ["};"]
    out += [f"static const uint8_t LED_X[LED_CHAIN_LEN] = {arr(lx)};",
            f"static const uint8_t LED_Y[LED_CHAIN_LEN] = {arr(ly)};"]
    out += [f"#define {name} {led_of_ref[ref]}" for name, ref in locks]
    return out


def restore_ref():
    return next(s["ref"] for s in layout.load_switches() if s["val"] == "Restore")


def led_map(switches, rev3, bench):
    by_ref = {s["ref"]: s for s in layout.load_switches()}
    locks = [("LED_LOCK_SHIFT", "SW89"), ("LED_LOCK_CAPS", "SW91"), ("LED_LOCK_4080", "SW92")]
    order, _ = layout.led_chain()
    chain = [(by_ref[r]["x"], by_ref[r]["y"]) for r in order]
    rev3_led = {r: i for i, r in enumerate(order)}
    # bench strip: each key takes the strip LED nearest its x position
    x0 = min(s["x"] for s in switches)
    x1 = max(s["x"] for s in switches)
    bench_led = {s["ref"]: round((s["x"] - x0) * (BENCH_STRIP - 1) / (x1 - x0))
                 for s in switches + [by_ref[restore_ref()]]}
    # RESTORE is not in the matrix (its own sense line), but has an LED
    locks = locks + [("LED_RESTORE", restore_ref())]
    strip = [(x0 + i * (x1 - x0) / (BENCH_STRIP - 1), 0.0) for i in range(BENCH_STRIP)]
    lines = [
        "// Generated by firmware/tools/gen_keymap.py from layout/switches.json.  Do not edit.",
        "// LED_OF_KEY[row][col]: the LED under a scanned key (LED_NONE: none).  LED_X / LED_Y: each",
        "// LED's place on the board, 0-255 left to right and back to front.  LED_LOCK_*: the lock",
        "// keys' LEDs.  Rev 3: the board's chain (lock keys first, then a snake through the rows);",
        "// bench: a 60-LED strip, keys mapped onto it by x.",
        "#pragma once",
        "#include <stdint.h>",
        '#include "keymap.h"',
        "#define LED_NONE 0xFF",
        "#if BOARD_REV3",
    ]
    lines += led_tables(chain, rev3_led, rev3, layout.PHYS_ROWS, layout.PHYS_COLS, locks)
    lines += ["#else"] + led_tables(strip, bench_led, bench, 8, 12, locks) + ["#endif"]
    with open(LED_OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", LED_OUT)


if __name__ == "__main__":
    main()
