#!/usr/bin/env python3
"""Regenerate main/keymap.h from layout/switches.json (physical row/col -> key legend)."""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
LAYOUT = os.path.join(HERE, "..", "..", "layout", "switches.json")
OUT = os.path.join(HERE, "..", "main", "keymap.h")
names = [[None] * 12 for _ in range(8)]
locks = {"SW89": (0, 11, "ShiftLock"), "SW91": (1, 11, "CapsLock"), "SW92": (2, 11, "40/80")}
for sw in json.load(open(LAYOUT, encoding="utf-8"))["switches"]:
    r = sw["ref"]
    if r in locks:
        row, col, name = locks[r]; names[row][col] = name; continue
    if sw["val"] == "Restore":
        continue
    m1 = re.match(r"ROW(\d+)", sw["row"] or ""); m2 = re.match(r"COL(\d+)", sw["col"] or "")
    if m1 and m2:
        names[int(m1.group(1))][int(m2.group(1))] = sw["val"]
with open(OUT, "w") as f:
    f.write("// Generated by firmware/tools/gen_keymap.py from layout/switches.json.  Do not edit.\n")
    f.write("// KEY_NAMES[row][col]: physical matrix position -> key legend.  Columns 0..10 are the\n")
    f.write("// C128 matrix (COL8..10 = K0..K2); column 11 carries the three lock keys (rev 3 only).\n")
    f.write("#pragma once\n#include <stddef.h>\n#define MATRIX_ROWS 8\n#define MATRIX_COLS 12\n#define HOST_COLS 11\n")
    f.write("static const char *const KEY_NAMES[MATRIX_ROWS][MATRIX_COLS] = {\n")
    for row in names:
        f.write("    {" + ", ".join(('"%s"' % n.replace('"', '\\"')) if n else "NULL" for n in row) + "},\n")
    f.write("};\n")
print("wrote", OUT)
